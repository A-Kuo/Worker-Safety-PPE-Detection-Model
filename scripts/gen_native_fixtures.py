#!/usr/bin/env python3
"""Generate parity fixtures for the experimental native port (``native/ppe-core``).

Each fixture is a raw detection tensor plus the detections the **Python runtime** produces for it
(``ppe.runtime.backends._decode_yolo_onnx``). The Rust tests decode the same tensor and must agree.
The Python test suite regenerates the fixtures in memory and fails if the committed files differ, so
a change to the Python decode cannot silently leave the native port behind.

    python scripts/gen_native_fixtures.py            # rewrite native/ppe-core/tests/fixtures/
    python scripts/gen_native_fixtures.py --check    # exit 1 if they are out of date

Plain text on purpose: the native crate has no dependencies, so no JSON parser.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from ppe.runtime.backends import _decode_yolo_onnx  # noqa: E402

FIXTURE_DIR = REPO / "native" / "ppe-core" / "tests" / "fixtures"
IOU = 0.45  # the runtime's fixed NMS threshold

# name, classes, anchors, original (w, h), imgsz, conf, seed, score sharpness
CASES = [
    ("vest_2class_landscape", 2, 240, (1280, 720), 640, 0.25, 1, 3.0),
    ("vest_2class_portrait_lowconf", 2, 240, (720, 1280), 640, 0.05, 2, 2.0),
    ("unified_14class", 14, 320, (1024, 683), 640, 0.25, 3, 4.0),
    ("nothing_above_threshold", 2, 64, (640, 480), 640, 0.99, 4, 6.0),
    ("small_input_square", 3, 48, (96, 96), 64, 0.30, 5, 2.0),
]


def letterbox_meta(w0: int, h0: int, imgsz: int) -> dict:
    """Same geometry as ``Letterboxer`` (kept in sync by tests/test_native_fixtures.py)."""
    scale = min(imgsz / h0, imgsz / w0)
    nw, nh = int(round(w0 * scale)), int(round(h0 * scale))
    return {"scale": scale, "pad": ((imgsz - nw) // 2, (imgsz - nh) // 2), "orig": (w0, h0), "imgsz": imgsz}


def make_tensor(nc: int, anchors: int, imgsz: int, seed: int, sharp: float) -> np.ndarray:
    """A (4+nc, anchors) float32 tensor with clustered, overlapping boxes so NMS has work to do."""
    rng = np.random.default_rng(seed)
    centres = rng.uniform(0.1 * imgsz, 0.9 * imgsz, size=(max(4, anchors // 12), 2))
    pick = rng.integers(0, len(centres), size=anchors)
    cxcy = centres[pick] + rng.normal(0, 0.03 * imgsz, size=(anchors, 2))
    wh = rng.uniform(0.05 * imgsz, 0.35 * imgsz, size=(anchors, 2))
    scores = rng.uniform(0, 1, size=(anchors, nc)) ** sharp
    return np.concatenate([cxcy, wh, scores], axis=1).T.astype(np.float32).copy()


def fmt(v: float) -> str:
    return f"{float(v):.9g}"  # enough digits to round-trip a float32


def build(name, nc, anchors, orig, imgsz, conf, seed, sharp) -> str:
    tensor = make_tensor(nc, anchors, imgsz, seed, sharp)
    meta = letterbox_meta(orig[0], orig[1], imgsz)
    names = {i: str(i) for i in range(nc)}
    dets = _decode_yolo_onnx([tensor[None, ...]], meta, conf=conf, names=names)
    lines = [
        "# ppe-core decode fixture v1. Generated by scripts/gen_native_fixtures.py - do not edit.",
        f"name {name}",
        f"channels {4 + nc}",
        f"anchors {anchors}",
        f"imgsz {imgsz}",
        f"orig {orig[0]} {orig[1]}",
        f"scale {meta['scale']!r}",
        f"pad {meta['pad'][0]} {meta['pad'][1]}",
        f"conf {fmt(np.float32(conf))}",
        f"iou {IOU}",
        "tensor",
    ]
    lines += [" ".join(fmt(v) for v in row) for row in tensor]
    lines.append(f"expect {len(dets)}")
    lines += [f"{d.cls_name} {fmt(d.conf)} " + " ".join(fmt(v) for v in d.xyxy) for d in dets]
    return "\n".join(lines) + "\n"


def generate() -> dict[str, str]:
    return {f"{case[0]}.txt": build(*case) for case in CASES}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the committed fixtures instead of writing")
    args = parser.parse_args()
    fixtures = generate()
    if args.check:
        stale = [n for n, text in fixtures.items()
                 if not (FIXTURE_DIR / n).is_file() or (FIXTURE_DIR / n).read_text(encoding="utf-8") != text]
        extra = sorted(p.name for p in FIXTURE_DIR.glob("*.txt") if p.name not in fixtures)
        if stale or extra:
            print(f"native fixtures out of date: stale={stale} unexpected={extra}", file=sys.stderr)
            return 1
        print(f"native fixtures up to date ({len(fixtures)})")
        return 0
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in fixtures.items():
        (FIXTURE_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {name}: {text.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
